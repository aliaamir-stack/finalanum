"use client";
import { FormEvent, useEffect, useMemo, useState, Suspense } from "react";
import { useRouter, useSearchParams } from "next/navigation";
import { AnimatePresence, motion } from "framer-motion";
import type { Occupant, Transaction, TransactionCategory, TransactionType } from "@/lib/types";
import { api } from "@/lib/api";
import { useAuth } from "@/lib/auth-context";
import { escapeHtml } from "@/lib/utils";

type StatusFilter = "ALL" | "pending" | "approved" | "rejected" | "cancelled";
type YearFilter = "ALL" | 2023 | 2024 | 2025 | 2026 | 2027;
const years: YearFilter[] = ["ALL", 2023, 2024, 2025, 2026, 2027];
const TREASURERS = ["Naveed", "Asif", "Dilshad", "Ali", "Danish"] as const;
const fmt = (v: string) => `₨ ${Number(v).toLocaleString("en-PK", { maximumFractionDigits: 0 })}`;
const fmtDate = (v: string) => { const d = new Date(v); return isNaN(d.getTime()) ? v : d.toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" }); };

const statusColors: Record<string, string> = {
  pending: "bg-amber-100 text-amber-700",
  approved: "bg-emerald-100 text-emerald-700",
  rejected: "bg-rose-100 text-rose-700",
  cancelled: "bg-slate-200 text-slate-600",
};

function downloadReceiptHtml(tx: Transaction, occupantLabel: string) {
  const ref = tx.receipt_no || `TXN-${tx.id}`;
  const html = `<!doctype html>
<html><head><meta charset="utf-8" /><title>Receipt ${escapeHtml(ref)}</title>
<style>
  @page { size: A4; margin: 18mm; }
  body { font-family: 'Segoe UI', Arial, sans-serif; color: #0f172a; }
  .header { display: flex; justify-content: space-between; align-items: flex-start; border-bottom: 2px solid #0f172a; padding-bottom: 12px; }
  .header h1 { margin: 0; font-size: 24px; }
  .header p { margin: 2px 0; color: #64748b; font-size: 12px; }
  .meta { margin-top: 20px; display: grid; grid-template-columns: 1fr 1fr; gap: 12px; font-size: 13px; }
  .meta div { padding: 6px 0; }
  .label { color: #64748b; font-size: 11px; text-transform: uppercase; letter-spacing: 0.06em; }
  .value { font-weight: 600; margin-top: 2px; }
  .amount-box { margin-top: 24px; padding: 18px; border: 2px solid #16a34a; border-radius: 8px; text-align: center; }
  .amount-box .label { color: #16a34a; font-weight: 600; }
  .amount-box .amount { font-size: 32px; font-weight: 700; color: #16a34a; margin-top: 4px; }
  .footer { margin-top: 36px; padding-top: 12px; border-top: 1px solid #e2e8f0; font-size: 11px; color: #64748b; display: flex; justify-content: space-between; }
  .stamp { margin-top: 28px; padding: 8px 14px; display: inline-block; border: 1px solid #16a34a; color: #16a34a; font-weight: 700; letter-spacing: 0.1em; border-radius: 6px; }
</style></head>
<body>
  <div class="header">
    <div>
      <h1>Anum Vista</h1>
      <p>Maintenance / Inflow Receipt</p>
    </div>
    <div style="text-align:right">
      <p><strong>Receipt #</strong></p>
      <p style="font-family:monospace">${escapeHtml(ref)}</p>
    </div>
  </div>

  <div class="meta">
    <div><div class="label">Issued To</div><div class="value">${escapeHtml(occupantLabel)}</div></div>
    <div><div class="label">Date</div><div class="value">${fmtDate(tx.date)}</div></div>
    <div><div class="label">Category</div><div class="value">${escapeHtml((tx.category ?? "").replace(/_/g, " ").toUpperCase())}</div></div>
    <div><div class="label">Type</div><div class="value">${escapeHtml(tx.type)}</div></div>
    <div><div class="label">Credited To (Treasurer)</div><div class="value">${escapeHtml(tx.credited_to ?? "—")}</div></div>
    <div><div class="label">Generated By</div><div class="value">${escapeHtml(tx.generated_by ?? "System")}</div></div>
    <div><div class="label">Approved At</div><div class="value">${tx.approved_at ? fmtDate(tx.approved_at) : "—"}</div></div>
    <div><div class="label">Status</div><div class="value">${escapeHtml(tx.status ?? "approved")}</div></div>
    <div style="grid-column: 1 / -1"><div class="label">Notes</div><div class="value">${escapeHtml(tx.notes ?? "—")}</div></div>
  </div>

  <div class="amount-box">
    <div class="label">Amount Received</div>
    <div class="amount">${fmt(tx.amount)}</div>
  </div>

  <div class="stamp">APPROVED</div>

  <div class="footer">
    <div>Anum Vista Property Management</div>
    <div>Printed ${new Date().toLocaleString("en-GB")}</div>
  </div>
  <script>window.onafterprint = () => window.close();</script>
</body></html>`;
  const w = window.open("", "_blank");
  if (!w) return;
  w.document.open();
  w.document.write(html);
  w.document.close();
  w.focus();
  setTimeout(() => w.print(), 350);
}

function TransactionsContent() {
  const { user } = useAuth();
  const router = useRouter();
  const isSuperAdmin = user?.role === "super_admin";
  const isAdmin = user?.role === "admin";
  const [transactions, setTransactions] = useState<Transaction[]>([]);
  const [tenants, setTenants] = useState<Occupant[]>([]);
  const [isLoading, setIsLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [successMsg, setSuccessMsg] = useState<string | null>(null);
  const [statusFilter, setStatusFilter] = useState<StatusFilter>("ALL");
  const [searchQuery, setSearchQuery] = useState("");
  const [selectedYear, setSelectedYear] = useState<YearFilter>("ALL");
  const [expandedId, setExpandedId] = useState<number | null>(null);
  const [createOpen, setCreateOpen] = useState(false);
  const [rejectId, setRejectId] = useState<number | null>(null);
  const [rejectReason, setRejectReason] = useState("");
  const [cancelId, setCancelId] = useState<number | null>(null);
  const [cancelReason, setCancelReason] = useState("");
  const searchParams = useSearchParams();
  const requestedTab = searchParams.get("tab");
  const currentTab = isAdmin ? "outflow" : (requestedTab || "inflow");

  // Force admin off the inflow tab
  useEffect(() => {
    if (isAdmin && requestedTab !== "outflow") {
      router.replace("/transactions?tab=outflow");
    }
  }, [isAdmin, requestedTab, router]);

  // Form state
  const [date, setDate] = useState("");
  const [amount, setAmount] = useState("");
  const [type, setType] = useState<TransactionType>("OUTFLOW");
  const [category, setCategory] = useState<TransactionCategory>("expense");
  const [occupantId, setOccupantId] = useState("");
  const [notes, setNotes] = useState("");
  const [generatedBy, setGeneratedBy] = useState<"Naveed" | "Dilshad" | "System">("System");
  const [expDesc, setExpDesc] = useState("");
  const [expDetails, setExpDetails] = useState("");
  const [creditedTo, setCreditedTo] = useState(""); // treasurer (OUTFLOW source / TRANSFER destination)
  const [transferFrom, setTransferFrom] = useState(""); // TRANSFER source
  const [paymentMode, setPaymentMode] = useState("");
  const [expDescriptions, setExpDescriptions] = useState<string[]>([]);
  const [isSubmitting, setIsSubmitting] = useState(false);

  const loadData = async () => {
    const [t, o] = await Promise.all([api.getTransactions(), api.getTenants()]);
    setTransactions(t); setTenants(o);
  };
  useEffect(() => { setIsLoading(true); loadData().catch(() => setError("Failed to load")).finally(() => setIsLoading(false)); }, []);
  useEffect(() => { api.getExpenseDescriptions().then(i => setExpDescriptions(i.map(x => x.label))).catch(() => {}); }, []);

  const occupantMap = useMemo(() => { const m = new Map<number, string>(); tenants.forEach(t => m.set(t.id, `${t.name} - ${t.unit.unit_no}`)); return m; }, [tenants]);

  const pendingApprovals = useMemo(() => {
    return transactions.filter((t) => {
      if (t.status !== "pending") return false;
      const isTabMatch = currentTab === "inflow" ? t.type === "INFLOW" : t.type !== "INFLOW";
      return isTabMatch;
    });
  }, [transactions, currentTab]);

  useEffect(() => {
    const params = new URLSearchParams(window.location.search);
    if (params.get("focus") !== "pending") return;
    const el = document.getElementById("pending-approvals");
    if (el) el.scrollIntoView({ behavior: "smooth", block: "start" });
  }, [transactions.length]);

  const filtered = useMemo(() => {
    const q = searchQuery.trim().toLowerCase();
    return transactions.filter(tx => {
      const yr = selectedYear === "ALL" || new Date(tx.date).getFullYear() === selectedYear;
      const label = tx.occupant_id ? occupantMap.get(tx.occupant_id) || "" : "General";
      const search = !q || label.toLowerCase().includes(q) || (tx.notes || "").toLowerCase().includes(q);
      const status = statusFilter === "ALL" || tx.status === statusFilter;
      const isTabMatch = currentTab === "inflow" ? tx.type === "INFLOW" : tx.type !== "INFLOW";
      return yr && search && status && isTabMatch;
    });
  }, [transactions, searchQuery, selectedYear, statusFilter, occupantMap, currentTab]);

  const handleApprove = async (id: number) => {
    try {
      await api.approveTransaction(id);
      await loadData();
      setStatusFilter("approved");
      setSuccessMsg("Transaction approved");
      setTimeout(() => setSuccessMsg(null), 3000);
    }
    catch (e) { setError((e as Error).message); }
  };
  const handleReject = async () => {
    if (!rejectId) return;
    try { await api.rejectTransaction(rejectId, rejectReason); setRejectId(null); setRejectReason(""); await loadData(); setSuccessMsg("Transaction rejected"); setTimeout(() => setSuccessMsg(null), 3000); }
    catch (e) { setError((e as Error).message); }
  };
  const handleCancel = async () => {
    if (!cancelId) return;
    try { await api.cancelTransaction(cancelId, cancelReason); setCancelId(null); setCancelReason(""); await loadData(); setSuccessMsg("Transaction cancelled"); setTimeout(() => setSuccessMsg(null), 3000); }
    catch (e) { setError((e as Error).message); }
  };

  const resetForm = () => {
    setDate(""); setAmount(""); setOccupantId(""); setNotes("");
    setCreditedTo(""); setTransferFrom(""); setPaymentMode(""); setExpDesc(""); setExpDetails("");
    setType("OUTFLOW"); setCategory("expense");
  };

  const handleSubmit = async (e: FormEvent) => {
    e.preventDefault();
    setIsSubmitting(true);
    try {
      if (type === "TRANSFER") {
        if (!transferFrom || !creditedTo) throw new Error("Select both transfer from and transfer to");
        if (transferFrom === creditedTo) throw new Error("Transfer source and destination cannot be the same");
        await api.createTransaction({
          date: `${date}T00:00:00`,
          amount,
          type: "TRANSFER",
          category: "other",
          generated_by: generatedBy,
          notes: notes || undefined,
          expense_details: expDetails || undefined,
          credited_to: creditedTo,
          transfer_from: transferFrom,
          payment_mode: (paymentMode as any) || undefined,
        });
      } else {
        const showExpense = type === "OUTFLOW" || category === "expense";
        await api.createTransaction({
          date: `${date}T00:00:00`,
          amount,
          type,
          category,
          occupant_id: occupantId ? Number(occupantId) : undefined,
          generated_by: generatedBy,
          notes: notes || undefined,
          expense_description: showExpense ? expDesc || undefined : undefined,
          expense_details: showExpense ? expDetails || undefined : undefined,
          credited_to: creditedTo || undefined,
          payment_mode: (paymentMode as any) || undefined,
        });
      }
      await loadData();
      setSuccessMsg(isSuperAdmin ? "Transaction logged" : "Submitted for Super Admin approval");
      resetForm();
      setCreateOpen(false);
      setTimeout(() => setSuccessMsg(null), 3000);
    } catch (err) {
      setError((err as Error).message);
    } finally {
      setIsSubmitting(false);
    }
  };

  const titleText = currentTab === "inflow" ? "Expenses — Inflow" : "Expenses — Outflow";

  return (
    <section className="space-y-6">
      <div className="flex justify-between items-end">
        <div>
          <h2 className="text-2xl font-semibold text-slate-900">{titleText}</h2>
          <p className="text-sm text-slate-600">
            {isLoading ? "Loading..." : `${filtered.length} visible`}
          </p>
        </div>
      </div>
      {successMsg && <div className="p-3 bg-emerald-50 text-emerald-700 rounded-lg border border-emerald-200">{successMsg}</div>}
      {error && <div className="p-3 bg-red-50 text-red-700 rounded-lg border border-red-200">{error} <button onClick={() => setError(null)} className="ml-2 underline">dismiss</button></div>}

      {/* Pending Approvals Section (Super Admin) */}
      {isSuperAdmin && pendingApprovals.length > 0 && (
        <div id="pending-approvals" className="rounded-2xl border-2 border-amber-300 bg-amber-50 p-5 space-y-3">
          <div className="flex items-center gap-2">
            <span className="flex h-3 w-3"><span className="absolute inline-flex h-3 w-3 animate-ping rounded-full bg-amber-400 opacity-75" /><span className="relative inline-flex h-3 w-3 rounded-full bg-amber-500" /></span>
            <h3 className="text-lg font-semibold text-amber-800">Pending Approvals ({pendingApprovals.length})</h3>
          </div>
          {pendingApprovals.map(tx => {
            const label = tx.occupant_id ? occupantMap.get(tx.occupant_id) || "Unknown" : "General";
            return (
              <div key={tx.id} className="rounded-xl bg-white border border-amber-200 p-4">
                <div className="flex items-center justify-between">
                  <div>
                    <p className="font-semibold text-slate-900">{label}</p>
                    <p className="text-sm text-slate-500">{fmtDate(tx.date)} · {tx.notes || "—"}</p>
                    {tx.type === "TRANSFER" ? (
                      <p className="text-xs text-slate-400 mt-1">Transfer: <span className="font-medium text-slate-600">{tx.transfer_from} → {tx.credited_to}</span></p>
                    ) : tx.credited_to ? (
                      <p className="text-xs text-slate-400 mt-1">Credited to: <span className="font-medium text-slate-600">{tx.credited_to}</span></p>
                    ) : null}
                  </div>
                  <p className={`text-lg font-bold ${tx.type === "INFLOW" ? "text-emerald-600" : tx.type === "OUTFLOW" ? "text-rose-600" : "text-sky-700"}`}>
                    {tx.type === "INFLOW" ? "+" : tx.type === "OUTFLOW" ? "-" : "↔"}{fmt(tx.amount)}
                  </p>
                </div>
                <div className="mt-3 flex gap-2">
                  <button onClick={() => handleApprove(tx.id)} className="rounded-lg bg-emerald-600 px-4 py-2 text-sm font-semibold text-white hover:bg-emerald-700 transition">✓ Approve</button>
                  <button onClick={() => setRejectId(tx.id)} className="rounded-lg bg-rose-600 px-4 py-2 text-sm font-semibold text-white hover:bg-rose-700 transition">✗ Reject</button>
                </div>
              </div>
            );
          })}
        </div>
      )}

      {/* Filters */}
      <div className="sticky top-4 z-20 rounded-2xl border border-slate-200 bg-white/95 p-3 shadow-sm backdrop-blur">
        <div className="flex flex-col gap-3 md:flex-row md:items-center md:justify-between">
          <div className="flex flex-1 flex-col gap-2 md:flex-row md:items-center">
            <input type="text" placeholder="Search..." value={searchQuery} onChange={e => setSearchQuery(e.target.value)} className="w-full rounded-xl border border-slate-300 px-4 py-2 text-sm outline-none md:max-w-xs" />
            <select value={selectedYear} onChange={e => setSelectedYear(e.target.value === "ALL" ? "ALL" : Number(e.target.value) as YearFilter)} className="rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none">
              {years.map(y => <option key={y} value={y}>{y === "ALL" ? "All Years" : y}</option>)}
            </select>
          </div>
          <div className="flex items-center gap-2 flex-wrap">
            {(["ALL", "pending", "approved", "rejected", "cancelled"] as StatusFilter[]).map(s => (
              <button key={s} onClick={() => setStatusFilter(s)} className={`rounded-full px-3 py-1.5 text-xs font-semibold transition ${statusFilter === s ? "bg-[#1e2a3a] text-white" : "bg-slate-100 text-slate-700 hover:bg-slate-200"}`}>
                {s === "ALL" ? "All" : s.charAt(0).toUpperCase() + s.slice(1)}
              </button>
            ))}
            {currentTab === "outflow" && (
              <button onClick={() => setCreateOpen(true)} className="rounded-xl bg-slate-900 px-4 py-2 text-sm font-semibold text-white hover:bg-slate-700">New Expense</button>
            )}
          </div>
        </div>
      </div>

      {/* Transaction List */}
      <div className="bg-white rounded-xl shadow-md overflow-hidden">
        <div className="p-4 flex justify-between items-center border-b"><h3 className="font-semibold">History</h3><p className="text-xs text-slate-500">{filtered.length} / {transactions.length}</p></div>
        <div className="p-4 space-y-3">
          {isLoading ? Array.from({ length: 6 }).map((_, i) => <div key={i} className="h-20 animate-pulse rounded-2xl bg-slate-200" />) :
           filtered.length === 0 ? <p className="text-sm text-slate-600">No transactions found.</p> :
           filtered.map(tx => {
             const isExp = expandedId === tx.id;
             const label = tx.occupant_id ? occupantMap.get(tx.occupant_id) || "Unknown" : "General";
             const txStatus = tx.status || "approved";
             const canDownloadReceipt = tx.type === "INFLOW" && txStatus === "approved";
             return (
               <motion.article key={tx.id} layout className="overflow-hidden rounded-2xl border border-slate-200 bg-white shadow-sm">
                 <button type="button" onClick={() => setExpandedId(isExp ? null : tx.id)} className="flex w-full items-center justify-between gap-4 px-5 py-4 text-left hover:bg-slate-50">
                   <div className="min-w-0 flex-1">
                     <div className="flex items-center gap-2">
                       <p className="text-sm text-slate-500">{fmtDate(tx.date)}</p>
                       <span className={`rounded-full px-2 py-0.5 text-[10px] font-semibold ${statusColors[txStatus] || "bg-slate-100 text-slate-600"}`}>{txStatus}</span>
                       {tx.type === "TRANSFER" && (
                         <span className="rounded-full bg-sky-100 px-2 py-0.5 text-[10px] font-semibold text-sky-700">TRANSFER</span>
                       )}
                     </div>
                     <p className="truncate text-base font-semibold text-slate-900">{label}</p>
                   </div>
                   <p className={`text-lg font-bold ${tx.type === "INFLOW" ? "text-green-500" : tx.type === "OUTFLOW" ? "text-red-500" : "text-sky-700"}`}>
                     {tx.type === "INFLOW" ? "+" : tx.type === "OUTFLOW" ? "-" : "↔"}{fmt(tx.amount)}
                   </p>
                 </button>
                 <AnimatePresence>{isExp && (
                   <motion.div initial={{ opacity: 0, height: 0 }} animate={{ opacity: 1, height: "auto" }} exit={{ opacity: 0, height: 0 }} className="border-t border-slate-100 px-5 py-4">
                     <div className="grid gap-2 text-sm text-slate-600 md:grid-cols-2">
                       <p><span className="font-semibold text-slate-800">Category:</span> {tx.category}</p>
                       <p><span className="font-semibold text-slate-800">Type:</span> {tx.type}</p>
                       <p><span className="font-semibold text-slate-800">Generated By:</span> {tx.generated_by || "System"}</p>
                       {tx.type === "TRANSFER" ? (
                         <>
                           <p><span className="font-semibold text-slate-800">Transfer From:</span> {tx.transfer_from || "—"}</p>
                           <p><span className="font-semibold text-slate-800">Transfer To:</span> {tx.credited_to || "—"}</p>
                         </>
                       ) : tx.credited_to ? (
                         <p><span className="font-semibold text-slate-800">Credited To:</span> {tx.credited_to}</p>
                       ) : null}
                       {tx.payment_mode && <p><span className="font-semibold text-slate-800">Payment Mode:</span> {tx.payment_mode.replace(/_/g, " ").replace(/\b\w/g, c => c.toUpperCase())}</p>}
                       {tx.receipt_no && <p><span className="font-semibold text-slate-800">Receipt #:</span> {tx.receipt_no}</p>}
                       {tx.expense_description && <p><span className="font-semibold text-slate-800">Description:</span> {tx.expense_description}</p>}
                       {tx.expense_details && <p className="md:col-span-2"><span className="font-semibold text-slate-800">Details:</span> {tx.expense_details}</p>}
                       {tx.rejection_reason && <p className="md:col-span-2"><span className="font-semibold text-rose-700">Rejection Reason:</span> {tx.rejection_reason}</p>}
                       {tx.cancel_reason && <p className="md:col-span-2"><span className="font-semibold text-slate-700">Cancel Reason:</span> {tx.cancel_reason}</p>}
                       {!isSuperAdmin && txStatus === "pending" && <p className="md:col-span-2"><span className="inline-flex rounded-full bg-amber-100 px-2 py-0.5 text-xs font-semibold text-amber-700">Awaiting Super Admin Approval</span></p>}
                       <p className="md:col-span-2"><span className="font-semibold text-slate-800">Notes:</span> {tx.notes || "—"}</p>
                     </div>
                     <div className="mt-3 flex flex-wrap gap-2">
                       {canDownloadReceipt && (
                         <>
                           <button
                             onClick={() => downloadReceiptHtml(tx, label)}
                             className="rounded-lg bg-emerald-600 px-3 py-1.5 text-xs font-semibold text-white hover:bg-emerald-700"
                           >
                             Print Receipt
                           </button>
                           <button
                             onClick={() => {
                               const url = api.getReceiptUrl(tx.id);
                               const token = localStorage.getItem("av_token");
                               window.open(`${url}${url.includes("?") ? "&" : "?"}token=${token}`, "_blank");
                             }}
                             className="rounded-lg bg-blue-600 px-3 py-1.5 text-xs font-semibold text-white hover:bg-blue-700"
                           >
                             PDF Receipt
                           </button>
                         </>
                       )}
                       {isSuperAdmin && txStatus === "approved" && (
                         <button onClick={() => setCancelId(tx.id)} className="rounded-lg bg-slate-200 px-3 py-1.5 text-xs font-semibold text-slate-700 hover:bg-slate-300">Cancel Transaction</button>
                       )}
                     </div>
                   </motion.div>
                 )}</AnimatePresence>
               </motion.article>
             );
           })}
        </div>
      </div>

      {/* Create Expense Modal */}
      <AnimatePresence>{createOpen && (
        <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} className="fixed inset-0 z-50 flex items-center justify-center bg-black/30">
          <motion.div initial={{ y: 40, opacity: 0 }} animate={{ y: 0, opacity: 1 }} exit={{ y: 40, opacity: 0 }} className="w-full max-w-2xl rounded-2xl bg-white p-6 shadow-xl max-h-[90vh] overflow-y-auto">
            <div className="mb-4 flex justify-between">
              <div><h3 className="text-xl font-semibold">Create Expense</h3></div>
              <button onClick={() => { setCreateOpen(false); resetForm(); }} className="text-sm font-semibold text-slate-500 hover:text-slate-700">Close</button>
            </div>

            <form className="grid grid-cols-1 gap-4 md:grid-cols-2" onSubmit={handleSubmit}>
              <div>
                <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Date</label>
                <input type="date" required value={date} onChange={e => setDate(e.target.value)} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none" />
              </div>
              <div>
                <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Amount</label>
                <input type="number" required min="1" value={amount} onChange={e => setAmount(e.target.value)} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none" />
              </div>
              <div>
                <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Type</label>
                <select value={type} onChange={e => setType(e.target.value as TransactionType)} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none">
                  <option value="OUTFLOW">OUTFLOW</option>
                  <option value="TRANSFER">TRANSFER</option>
                </select>
              </div>
              <div>
                <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Generated By</label>
                <select value={generatedBy} onChange={e => setGeneratedBy(e.target.value as "Naveed" | "Dilshad" | "System")} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none">
                  <option>Naveed</option><option>Dilshad</option><option>System</option>
                </select>
              </div>

              {type === "TRANSFER" ? (
                <>
                  <div>
                    <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Transfer From</label>
                    <select required value={transferFrom} onChange={e => setTransferFrom(e.target.value)} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none">
                      <option value="">Select Treasurer...</option>
                      {TREASURERS.map(t => <option key={t} value={t}>{t}</option>)}
                    </select>
                  </div>
                  <div>
                    <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Transfer To</label>
                    <select required value={creditedTo} onChange={e => setCreditedTo(e.target.value)} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none">
                      <option value="">Select Treasurer...</option>
                      {TREASURERS.map(t => <option key={t} value={t}>{t}</option>)}
                    </select>
                  </div>
                  <div>
                    <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Payment Mode</label>
                    <select value={paymentMode} onChange={e => setPaymentMode(e.target.value)} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none">
                      <option value="">Select...</option>
                      <option value="cash">Cash</option>
                      <option value="bank_transfer">Bank Transfer</option>
                      <option value="cheque">Cheque</option>
                      <option value="online">Online</option>
                      <option value="other">Other</option>
                    </select>
                  </div>
                  <div className="md:col-span-2">
                    <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Notes</label>
                    <input type="text" value={notes} onChange={e => setNotes(e.target.value)} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none" />
                  </div>
                  <div className="md:col-span-2">
                    <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Details</label>
                    <input type="text" value={expDetails} onChange={e => setExpDetails(e.target.value)} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none" />
                  </div>
                </>
              ) : (
                <>
                  <div>
                    <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Category</label>
                    <select value={category} onChange={e => setCategory(e.target.value as TransactionCategory)} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none">
                      <option value="expense">Expense</option>
                      <option value="ad_revenue">Ad Revenue</option>
                      <option value="other">Other</option>
                    </select>
                  </div>
                  <div className="md:col-span-2">
                    <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Occupant</label>
                    <select value={occupantId} onChange={e => setOccupantId(e.target.value)} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none">
                      <option value="">General</option>
                      {tenants.map(t => <option key={t.id} value={t.id}>{t.unit.unit_no} — {t.name}</option>)}
                    </select>
                  </div>
                  <div>
                    <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Notes</label>
                    <input type="text" value={notes} onChange={e => setNotes(e.target.value)} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none" />
                  </div>
                  <div>
                    <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Paid By (Treasurer)</label>
                    <select value={creditedTo} onChange={e => setCreditedTo(e.target.value)} required className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none">
                      <option value="">Select Treasurer...</option>
                      {TREASURERS.map(t => <option key={t} value={t}>{t}</option>)}
                    </select>
                  </div>
                  <div>
                    <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Payment Mode</label>
                    <select value={paymentMode} onChange={e => setPaymentMode(e.target.value)} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none">
                      <option value="">Select...</option>
                      <option value="cash">Cash</option>
                      <option value="bank_transfer">Bank Transfer</option>
                      <option value="cheque">Cheque</option>
                      <option value="online">Online</option>
                      <option value="other">Other</option>
                    </select>
                  </div>
                  <div>
                    <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Description</label>
                    <select value={expDesc} onChange={e => setExpDesc(e.target.value)} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none">
                      <option value="">Select...</option>
                      {expDescriptions.map(l => <option key={l} value={l}>{l}</option>)}
                    </select>
                  </div>
                  <div className="md:col-span-2">
                    <label className="mb-1 block text-xs font-semibold uppercase text-slate-500">Details</label>
                    <input type="text" value={expDetails} onChange={e => setExpDetails(e.target.value)} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none" />
                  </div>
                </>
              )}

              <button type="submit" disabled={isSubmitting} className="md:col-span-2 rounded-xl bg-slate-900 px-4 py-2 text-sm font-semibold text-white hover:bg-slate-700 disabled:opacity-50">
                {isSubmitting ? "Saving..." : "Create"}
              </button>
            </form>
          </motion.div>
        </motion.div>
      )}</AnimatePresence>

      {/* Reject Modal */}
      <AnimatePresence>{rejectId !== null && (
        <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} className="fixed inset-0 z-50 flex items-center justify-center bg-black/30">
          <motion.div initial={{ y: 20 }} animate={{ y: 0 }} className="w-full max-w-md rounded-2xl bg-white p-6 shadow-xl">
            <h3 className="text-lg font-semibold text-slate-900 mb-2">Reject Transaction</h3>
            <p className="text-sm text-slate-500 mb-4">Provide a reason for rejection:</p>
            <textarea value={rejectReason} onChange={e => setRejectReason(e.target.value)} rows={3} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none mb-4" placeholder="Reason..." />
            <div className="flex gap-2 justify-end">
              <button onClick={() => { setRejectId(null); setRejectReason(""); }} className="rounded-lg px-4 py-2 text-sm font-semibold text-slate-600 hover:bg-slate-100">Cancel</button>
              <button onClick={handleReject} className="rounded-lg bg-rose-600 px-4 py-2 text-sm font-semibold text-white hover:bg-rose-700">Reject</button>
            </div>
          </motion.div>
        </motion.div>
      )}</AnimatePresence>

      {/* Cancel Modal */}
      <AnimatePresence>{cancelId !== null && (
        <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} className="fixed inset-0 z-50 flex items-center justify-center bg-black/30">
          <motion.div initial={{ y: 20 }} animate={{ y: 0 }} className="w-full max-w-md rounded-2xl bg-white p-6 shadow-xl">
            <h3 className="text-lg font-semibold text-slate-900 mb-2">Cancel Transaction</h3>
            <p className="text-sm text-slate-500 mb-4">This will not delete the record. Provide a reason:</p>
            <textarea value={cancelReason} onChange={e => setCancelReason(e.target.value)} rows={3} className="w-full rounded-xl border border-slate-300 px-3 py-2 text-sm outline-none mb-4" placeholder="Reason..." />
            <div className="flex gap-2 justify-end">
              <button onClick={() => { setCancelId(null); setCancelReason(""); }} className="rounded-lg px-4 py-2 text-sm font-semibold text-slate-600 hover:bg-slate-100">Back</button>
              <button onClick={handleCancel} className="rounded-lg bg-slate-800 px-4 py-2 text-sm font-semibold text-white hover:bg-slate-700">Cancel Transaction</button>
            </div>
          </motion.div>
        </motion.div>
      )}</AnimatePresence>
    </section>
  );
}

export default function TransactionsPage() {
  return (
    <Suspense fallback={<div className="p-8 text-slate-500">Loading...</div>}>
      <TransactionsContent />
    </Suspense>
  );
}
